ALTER SESSION SET CONTAINER = XEPDB1;
ALTER SESSION SET NLS_DATE_FORMAT = 'DD/MM/YYYY';

BEGIN EXECUTE IMMEDIATE 'DROP TABLE TELCO.MONTHLY_STATS CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE TELCO.CUSTOMERS CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE TELCO.TARIFFS CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE TABLE TELCO.TARIFFS (
    TARIFF_ID     NUMBER(5)      PRIMARY KEY,
    NAME          VARCHAR2(100)  NOT NULL,
    MONTHLY_FEE   NUMBER(10,2)   NOT NULL,
    DATA_LIMIT    NUMBER(10)     NOT NULL,
    MINUTE_LIMIT  NUMBER(10)     NOT NULL,
    SMS_LIMIT     NUMBER(10)     NOT NULL
);

CREATE TABLE TELCO.CUSTOMERS (
    CUSTOMER_ID  NUMBER(10)     PRIMARY KEY,
    NAME         VARCHAR2(100)  NOT NULL,
    CITY         VARCHAR2(100)  NOT NULL,
    SIGNUP_DATE  DATE           NOT NULL,
    TARIFF_ID    NUMBER(5)      NOT NULL REFERENCES TELCO.TARIFFS(TARIFF_ID)
);

CREATE TABLE TELCO.MONTHLY_STATS (
    ID             NUMBER(10)     PRIMARY KEY,
    CUSTOMER_ID    NUMBER(10)     NOT NULL UNIQUE REFERENCES TELCO.CUSTOMERS(CUSTOMER_ID),
    DATA_USAGE     NUMBER(12,2)   NOT NULL,
    MINUTE_USAGE   NUMBER(10)     NOT NULL,
    SMS_USAGE      NUMBER(10)     NOT NULL,
    PAYMENT_STATUS VARCHAR2(20)   NOT NULL
);

CREATE INDEX TELCO.IDX_CUSTOMERS_TARIFF ON TELCO.CUSTOMERS(TARIFF_ID);
CREATE INDEX TELCO.IDX_CUSTOMERS_CITY   ON TELCO.CUSTOMERS(CITY);
CREATE INDEX TELCO.IDX_CUSTOMERS_SIGNUP ON TELCO.CUSTOMERS(SIGNUP_DATE);
CREATE INDEX TELCO.IDX_STATS_PAYMENT    ON TELCO.MONTHLY_STATS(PAYMENT_STATUS);
